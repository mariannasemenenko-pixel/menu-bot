def apply_memory_updates(memory_data, updates):

    for update in updates:

        if not isinstance(update, dict):
            continue

        person = update.get("person")
        field = update.get("field")
        value = update.get("value")

        if person not in [
            "marianna",
            "pavel",
            "shared"
        ]:
            continue

        if not field:
            continue

        if person in [
            "marianna",
            "pavel"
        ]:

            if field in [
                "height_cm",
                "weight_kg",
                "goal"
            ]:

                memory_data[person][field] = value

            else:

                memory_data[person]["other"][field] = value

        else:

            if field == "food_at_home":

                if isinstance(value, dict):

                    memory_data[
                        "shared"
                    ][
                        "food_at_home"
                    ].update(value)

            elif field == "liked_dishes":

                if isinstance(value, list):

                    for item in value:

                        if item not in memory_data[
                            "shared"
                        ]["liked_dishes"]:

                            memory_data[
                                "shared"
                            ]["liked_dishes"].append(item)

            elif field == "disliked_dishes":

                if isinstance(value, list):

                    for item in value:

                        if item not in memory_data[
                            "shared"
                        ]["disliked_dishes"]:

                            memory_data[
                                "shared"
                            ]["disliked_dishes"].append(item)

            elif field == "dish_rating":

                memory_data[
                    "shared"
                ]["dish_ratings"].append(value)

            elif field == "current_menu":

                memory_data[
                    "shared"
                ]["current_menu"] = value

            elif field == "menu_history":

                if isinstance(value, list):

                    memory_data[
                        "shared"
                    ]["menu_history"].extend(value)

    return memory_data



async def chat(update: Update, context: ContextTypes.DEFAULT_TYPE):

    if not update.message or not update.message.text:
        return

    user_id = str(update.effective_user.id)

    user_message = update.message.text.strip()

    print("MESSAGE:", user_message)

    # --------------------------------------------------------
    # 1. Загружаем память
    # --------------------------------------------------------

    memory_data = load_user_memory(
        user_id,
        update.effective_user.first_name
    )

    # --------------------------------------------------------
    # 2. Извлекаем новую информацию
    # --------------------------------------------------------

    updates = extract_memory(
        user_message,
        memory_data
    )

    if updates:

        print(
            "MEMORY UPDATES:",
            updates
        )

        memory_data = apply_memory_updates(
            memory_data,
            updates
        )

        save_user_memory(
            user_id,
            memory_data
        )

    # --------------------------------------------------------
    # 3. Компактная память для основного GPT
    # --------------------------------------------------------

    memory_context = json.dumps(
        memory_data,
        ensure_ascii=False,
        separators=(",", ":")
    )

    # Защита от чрезмерно большой памяти
    if len(memory_context) > 15000:

        memory_context = memory_context[:15000]

    prompt = f"""
ПОСТОЯННАЯ ПАМЯТЬ:

{memory_context}

СООБЩЕНИЕ ПОЛЬЗОВАТЕЛЯ:

{user_message}

Используй память как источник фактов.

ПРИОРИТЕТ:

1. Жёсткие ограничения из системного промпта.
2. Постоянные правила.
3. Сохранённые предпочтения и история.
4. Текущая просьба.

ВАЖНО:

- не спрашивай повторно то, что уже известно;
- данные Марианны и Павла не смешивай;
- если пользователь спрашивает конкретное сохранённое значение,
  ответь непосредственно;
- если пользователь просит новое меню — сразу составляй его;
- учитывай продукты дома;
- учитывай оценки и историю блюд;
- не придумывай отсутствующие данные;
- предпочтение не отменяет жёсткое ограничение;
- овощи Марианне запрещены, кроме картофеля, независимо от
  сохранённых предпочтений.

Если информации действительно не хватает для выполнения задачи,
задай только необходимый вопрос.
"""

    # --------------------------------------------------------
    # 4. Основной OpenAI
    # --------------------------------------------------------

    try:

        response = client.responses.create(
            model="gpt-5-mini",
            instructions=SYSTEM_PROMPT,
            input=prompt,
        )

        answer = response.output_text.strip()

        print("OPENAI OK")

    except Exception as e:

        print(
            "OPENAI ERROR:",
            repr(e)
        )

        await update.message.reply_text(
            "Произошла ошибка при обращении к ИИ 😔"
        )

        return

    # --------------------------------------------------------
    # 5. Отправляем ответ
    # --------------------------------------------------------

    try:

        await send_long_message(
            update.message,
            answer
        )

        print(
            "TELEGRAM RESPONSE SENT"
        )

    except Exception as e:

        print(
            "TELEGRAM ERROR:",
            repr(e)
        )



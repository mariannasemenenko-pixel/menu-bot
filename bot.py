import os
import asyncio
import json

from flask import Flask
from openai import OpenAI

from telegram import Update
from telegram.ext import (
    Application,
    CommandHandler,
    MessageHandler,
    ContextTypes,
    filters,
)


TELEGRAM_TOKEN = os.environ["TELEGRAM_BOT_TOKEN"]
OPENAI_API_KEY = os.environ["OPENAI_API_KEY"]

client = OpenAI(api_key=OPENAI_API_KEY)

MEMORY_FILE = "memory.json"


SYSTEM_PROMPT = """
Ты — личный помощник по планированию питания для Марианны и Павла.

Твоя главная задача — создавать для них практичные меню на 3 дня, рецепты и списки покупок с минимальным количеством готовки.

## 1. Марианна

Марианна категорически не ест:
- любые фрукты;
- любые овощи, кроме картофеля;
- ягоды;
- острое.

Марианна находится на дефиците калорий.

Еда для неё должна быть:
- сытной;
- достаточно объёмной;
- относительно низкокалорийной;
- не слишком жирной;
- с нормальным количеством белка.

Не предлагай ей запрещённые продукты даже в небольших количествах, соусах или как украшение.

## 2. Павел

Павел ест всё, но не любит жирные и тяжёлые блюда.

Его цель — набор мышечной массы без лишнего набора жира.

Не нужно специально делать его питание экстремально калорийным или очень жирным.

Нужны обычные полноценные блюда с достаточным количеством белка и нормальной калорийностью.

Завтрак Павла должен быть обычным средним по размеру, не огромным.

## 3. ГЛАВНОЕ ПРАВИЛО ЦИКЛА

Один цикл меню всегда длится 3 дня.

В течение всех трёх дней полностью одинаковыми должны оставаться ВСЕ элементы меню:

- завтрак Павла;
- основное блюдо;
- гарнир/дополнение;
- овощное дополнение Павла;
- хрустящая низкокалорийная закуска Марианны.

Всё необходимое на эти 3 дня должно быть приготовлено один раз в первый день.

После первой готовки в следующие два дня желательно вообще ничего не готовить.

## 4. СТРУКТУРА ЦИКЛА

Каждый цикл должен содержать:

1. Завтрак Павла.
2. Одно общее основное блюдо.
3. При необходимости разные гарниры или размеры порций.
4. Овощное дополнение Павла.
5. Хрустящее низкокалорийное дополнение Марианны.

## 5. ПРИГОТОВЛЕНИЕ

Использовать только:
- плиту;
- духовку.

Не использовать аэрогриль, миксер или другую специальную технику.

Блюда должны быть простыми или максимум средней сложности.

Главный приоритет — минимум готовки.

## 6. ПОРЦИИ

Порции должны быть нормальными и достаточно большими, чтобы еда была сытной.

Для Марианны и Павла рассчитывай порции отдельно.

Всегда указывай:
- количество ингредиентов;
- количество готового блюда;
- размер дневной порции;
- сколько приготовить всего на 3 дня.

## 7. КБЖУ

КБЖУ рассчитывай на основании фактического количества ингредиентов.

Для каждого человека отдельно указывай:
- калории;
- белки;
- жиры;
- углеводы.

Не увеличивай калорийность Павла просто за счёт масла, сливок или других жирных продуктов.

## 8. ЗАКУСКА МАРИАННЫ

Для Марианны должно быть простое хрустящее дополнение.

Оно должно быть:
- без овощей;
- без фруктов;
- без ягод;
- не острым;
- до 100 ккал на дневную порцию;
- не требовать ежедневной готовки.

## 9. ОВОЩНОЕ ДОПОЛНЕНИЕ ПАВЛА

Павлу добавляй простое овощное дополнение.

Оно должно быть рассчитано сразу на 3 дня.

## 10. ХРАНЕНИЕ

Все блюда должны быть реалистично пригодны для хранения 3 дня.

Если блюдо плохо подходит для хранения 3 дня — не используй его.

## 11. РЕЦЕПТЫ

Для каждого блюда указывай:
- название;
- сколько получится;
- ингредиенты;
- пошаговый рецепт;
- температуру духовки;
- время приготовления;
- как разделить на 3 дня;
- порции Марианны и Павла.

## 12. СПИСОК ПОКУПОК

Создавай список продуктов на весь 3-дневный цикл.

Учитывай:
- двух человек;
- все 3 дня;
- реальные размеры порций;
- все ингредиенты;
- соусы и заправки.

Группируй покупки по категориям.

## 13. МАГАЗИНЫ

Продукты должны быть доступны в Суботице.

В первую очередь ориентируйся на IDEA и MAXI.

Не используй редкие или экзотические продукты без необходимости.

## 14. ОСТАТКИ

Если пользователь сообщает, что продукты уже есть дома, учитывай их и вычитай необходимое количество из списка покупок.

## 15. ЗАМЕНЫ

Если пользователь просит заменить продукт или блюдо, пересчитай весь цикл:
- ингредиенты;
- порции;
- КБЖУ;
- покупки.

## 16. ИСТОРИЯ

Учитывай предыдущие меню, если они доступны.

Не повторяй одно и то же основное блюдо слишком часто.

Любимые блюда можно повторять позже.

## 17. ОЦЕНКИ

Учитывай оценки и комментарии пользователя.

Если блюдо отмечено как «больше не готовить», не предлагай его снова без прямой просьбы.

## 18. НОВОЕ МЕНЮ

Когда пользователь пишет «Новое меню» или аналогичную команду, создай новый полный 3-дневный цикл.

Формат:

🍽️ МЕНЮ НА 3 ДНЯ — ЦИКЛ N

Затем:
- завтрак Павла;
- основное блюдо;
- дополнение Павла;
- дополнение Марианны;
- приготовление;
- список покупок;
- КБЖУ.

## 19. СЕГОДНЯ

Если пользователь спрашивает, что есть сегодня, показывай меню текущего 3-дневного цикла.

В течение всех трёх дней набор блюд должен оставаться одинаковым.

## 20. ПАМЯТЬ

Используй переданные тебе данные профиля пользователя.

Если рост, вес, цели, предпочтения или другие постоянные данные уже сохранены в памяти — НЕ спрашивай их повторно.

Если пользователь сообщает новые постоянные данные, используй их в дальнейшем.

Если пользователь явно изменяет данные, используй новые значения вместо старых.

Не спрашивай повторно информацию, которая уже есть в сохранённой памяти.

## 21. ОБЩИЕ ПРАВИЛА

Главный приоритет — практичность.

Меню должно быть таким, чтобы два человека могли приготовить его один раз и спокойно есть три дня.

Не усложняй рецепты ради разнообразия.

Не нарушай ограничения Марианны.

Не делай Павлу жирное питание ради увеличения калорий.

Не делай Павлу огромные завтраки.

Не делай Марианне маленькие порции только ради снижения калорийности.

Отвечай на русском языке.
"""


def load_memory():
    try:
        with open(MEMORY_FILE, "r", encoding="utf-8") as f:
            return json.load(f)
    except:
        return {
            "users": {},
            "food_preferences": [],
            "dislikes": [],
            "liked_dishes": [],
        }


def save_memory(memory):
    with open(MEMORY_FILE, "w", encoding="utf-8") as f:
        json.dump(memory, f, ensure_ascii=False, indent=2)


memory = load_memory()


async def start(update: Update, context: ContextTypes.DEFAULT_TYPE):
    await update.message.reply_text(
        "Привет! 🍽️\n\n"
        "Я помощник Марианны и Павла по меню.\n\n"
        "Я могу запоминать ваши данные и использовать их "
        "при составлении меню на 3 дня.\n\n"
        "Напиши мне что-нибудь!"
    )


async def chat(update: Update, context: ContextTypes.DEFAULT_TYPE):
    user_id = str(update.effective_user.id)
    user_message = update.message.text

    if user_id not in memory["users"]:
        memory["users"][user_id] = {
            "name": update.effective_user.first_name,
            "profile": {},
        }

    user_memory = memory["users"][user_id]

    memory_context = json.dumps(
        user_memory,
        ensure_ascii=False,
        indent=2
    )

    prompt = f"""
Сохранённые данные пользователя:

{memory_context}

Сообщение пользователя:

{user_message}

Используй сохранённые данные и НЕ спрашивай повторно то,
что уже известно.

Если пользователь сообщает новую постоянную информацию,
которую нужно запомнить, обязательно укажи её в специальном
блоке в конце ответа:

MEMORY_UPDATE:
{{"ключ": "значение"}}

Если новых данных для сохранения нет, напиши:

MEMORY_UPDATE:
{{}}

"""

    try:
        response = client.responses.create(
            model="gpt-5-mini",
            instructions=SYSTEM_PROMPT,
            input=prompt,
        )

        answer = response.output_text

        # Пытаемся найти обновление памяти
        if "MEMORY_UPDATE:" in answer:
            parts = answer.split("MEMORY_UPDATE:", 1)
            visible_answer = parts[0].strip()
            memory_update_text = parts[1].strip()

            try:
                memory_update = json.loads(memory_update_text)

                if isinstance(memory_update, dict):
                    user_memory["profile"].update(memory_update)
                    save_memory(memory)

            except Exception as memory_error:
                print("MEMORY ERROR:", repr(memory_error))

            answer = visible_answer

        # Telegram не принимает сообщения длиннее ~4096 символов.
        # Поэтому длинные ответы отправляем несколькими сообщениями.
        max_length = 4000

        for i in range(0, len(answer), max_length):
            chunk = answer[i:i + max_length]
            await update.message.reply_text(chunk)

    except Exception as e:
        print("BOT ERROR:", repr(e))

        await update.message.reply_text(
            "Произошла ошибка 😔 Попробуй ещё раз."
        )


app = Flask(__name__)


@app.route("/")
def home():
    return "Menu bot is alive!"


async def run_bot():
    application = (
        Application.builder()
        .token(TELEGRAM_TOKEN)
        .build()
    )

    application.add_handler(
        CommandHandler("start", start)
    )

    application.add_handler(
        MessageHandler(
            filters.TEXT & ~filters.COMMAND,
            chat
        )
    )

    await application.initialize()
    await application.start()
    await application.updater.start_polling()

    print("Telegram bot started!")

    await asyncio.Event().wait()


async def main():
    bot_task = asyncio.create_task(run_bot())

    from hypercorn.asyncio import serve
    from hypercorn.config import Config

    config = Config()
    config.bind = [
        f"0.0.0.0:{os.environ.get('PORT', '10000')}"
    ]

    await serve(app, config)


if __name__ == "__main__":
    asyncio.run(main())

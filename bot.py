async def send_long_message(message, text):

    max_length = 3900

    if len(text) <= max_length:

        await message.reply_text(text)

        return

    while len(text) > max_length:

        cut = text.rfind(
            "\n",
            0,
            max_length
        )

        if cut < 1000:

            cut = max_length

        part = text[:cut]

        await message.reply_text(part)

        text = text[cut:].lstrip()

    if text:

        await message.reply_text(text)



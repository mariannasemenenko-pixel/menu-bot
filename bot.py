def load_user_memory(user_id, first_name):

    try:

        result = (
            supabase
            .table("bot_memory")
            .select("memory")
            .eq("user_id", user_id)
            .limit(1)
            .execute()
        )

        if result.data:

            data = result.data[0].get("memory")

            if isinstance(data, dict):

                data = migrate_memory(data)

                return data

    except Exception as e:

        print(
            "SUPABASE LOAD ERROR:",
            repr(e)
        )

    data = empty_memory()

    data["marianna"]["other"]["user_name"] = first_name

    return data


